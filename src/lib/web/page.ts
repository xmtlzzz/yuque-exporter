// The single-page UI. It is rendered server-side only to inject the session
// nonce; everything else is inline, so the UI needs no build step of its own.
import { THEME } from './theme.js';

export interface PageOptions {
  session: string;
}

// The nonce is hex in practice, but it is still serialised as JSON and then
// stripped of characters that could terminate the script element.
function injectSession(script: string, session: string): string {
  const literal = JSON.stringify(session).replace(/</g, '\\u003c').replace(/>/g, '\\u003e');
  return script.replace('__SESSION_JSON__', literal);
}

const SCRIPT = [
  'const SESSION=__SESSION_JSON__;',
  'const $=id=>document.getElementById(id);',
  'let selected=new Set(),timer=null,lastRunning=false,repos=[],query="",inSetup=false;',
  'async function api(url,opt){const r=await fetch(url,opt);const d=await r.json().catch(()=>({}));',
  'if(!r.ok)throw new Error(d.error||("HTTP "+r.status));return d;}',
  'function setHint(t){$("hint").textContent=t||"";}',
  'function visibleRepos(){if(!query)return repos;const q=query.toLowerCase();',
  'return repos.filter(r=>r.name.toLowerCase().includes(q)||r.namespace.toLowerCase().includes(q));}',
  'function syncSelectAll(){const vis=visibleRepos();',
  'const on=vis.filter(r=>selected.has(r.namespace)).length;',
  'const box=$("selectAll");',
  'box.checked=vis.length>0&&on===vis.length;',
  'box.indeterminate=on>0&&on<vis.length;',
  'box.disabled=vis.length===0;',
  '$("visibleCount").textContent=query?("匹配 "+vis.length+" 个"):(vis.length+" 个知识库");}',
  'function syncCount(){const items=repos.filter(r=>selected.has(r.namespace));',
  'const docs=items.reduce((s,r)=>s+(r.items||0),0);',
  '$("count").textContent="已选 "+items.length+" 个知识库 · "+docs+" 篇";',
  'const b=$("start");b.disabled=lastRunning||items.length===0;',
  'b.textContent=items.length?("开始导出（"+items.length+"）"):"开始导出";',
  'syncSelectAll();}',
  'function addNote(host,text){const p=document.createElement("p");p.className="muted";',
  'p.textContent=text;host.append(p);}',
  'function renderList(){',
  'const vis=visibleRepos();const host=$("list");host.textContent="";',
  'if(!repos.length){addNote(host,"这个账号下还没有知识库。");syncCount();return;}',
  'if(!vis.length){addNote(host,"没有匹配的知识库。");syncCount();return;}',
  'for(const repo of vis){',
  'const row=document.createElement("label");row.className="item";',
  'const box=document.createElement("input");box.type="checkbox";',
  'box.value=repo.namespace;box.checked=selected.has(repo.namespace);',
  'box.onchange=()=>{if(box.checked)selected.add(repo.namespace);',
  'else selected.delete(repo.namespace);row.classList.toggle("on",box.checked);syncCount();};',
  'const name=document.createElement("span");name.className="name";name.textContent=repo.name;',
  'const meta=document.createElement("span");meta.className="meta";meta.textContent=repo.items+" 篇";',
  'row.classList.toggle("on",box.checked);row.append(box,name,meta);host.append(row);}',
  'syncCount();}',
  'function showSetup(on,msg){',
  'inSetup=on;',
  '$("setupPanel").hidden=!on;$("mainPanel").hidden=on;',
  // A previous run's report is irrelevant while the app has no token, and the
  // poll loop below would otherwise reveal it again on the next tick.
  '$("resultPanel").hidden=on||$("resultPanel").hidden;',
  'if(on)$("progressPanel").hidden=true;',
  '$("who").textContent=on?"需要先配置 Token":"正在读取账号…";',
  'if(msg)$("tokenHint").textContent=msg;}',
  'async function loadRepos(){const host=$("list");host.textContent="";',
  'addNote(host,"正在加载知识库…");',
  'try{const d=await api("/api/repos");repos=d.repos||[];',
  'showSetup(false);',
  '$("who").textContent=d.name+"（"+d.login+"）· 共 "+repos.length+" 个知识库";',
  'selected=new Set();renderList();}',
  'catch(e){',
  'if(e.message==="NO_TOKEN"){showSetup(true);return;}',
  'host.textContent="";addNote(host,e.message);}}',
  '$("saveToken").onclick=async()=>{',
  'const t=$("tokenInput").value.trim();if(!t){$("tokenHint").textContent="请先粘贴 Token";return;}',
  '$("saveToken").disabled=true;$("tokenHint").textContent="正在验证…";',
  'try{const r=await api("/api/token",{method:"POST",',
  'headers:{"content-type":"application/json"},',
  'body:JSON.stringify({session:SESSION,token:t})});',
  '$("tokenInput").value="";$("tokenHint").textContent="";await loadRepos();}',
  'catch(e){$("tokenHint").textContent=e.message;}',
  'finally{$("saveToken").disabled=false;}};',
  '$("tokenInput").onkeydown=e=>{if(e.key==="Enter")$("saveToken").click();};',
  '$("openTokenPage").onclick=()=>{window.open("https://www.yuque.com/settings/tokens","_blank");};',
  'async function poll(){try{const d=await api("/api/status");',
  '$("progressPanel").hidden=!d.running&&!d.lastResult;',
  'lastRunning=!!d.running;syncCount();',
  'if(d.running){setHint("导出进行中…");',
  'const secs=Math.round((Date.now()-d.running.startedAt)/1000);',
  '$("progressText").textContent="已运行 "+secs+" 秒";',
  'const log=$("log");log.textContent=d.running.log.join(String.fromCharCode(10));',
  'log.scrollTop=log.scrollHeight;',
  'const done=d.running.log.filter(l=>l.includes("Exported ")).length;',
  '$("barFill").style.width=Math.min(95,done?15+done:8)+"%";}',
  'else{setHint("");if(d.lastResult)$("barFill").style.width="100%";}',
  'if(d.report&&!inSetup){$("resultPanel").hidden=false;',
  'const s=d.report.summary||{};const stats=$("stats");stats.textContent="";',
  'for(const k of Object.keys(s)){const div=document.createElement("div");',
  'div.className="stat"+(k==="failed"&&s[k]?" warn":"");',
  'const b=document.createElement("b");b.textContent=s[k];',
  'const t=document.createElement("span");t.textContent=k;',
  'div.append(b,t);stats.append(div);}',
  '$("outDir").textContent="输出目录："+((d.report.outputDir)||d.outputDir||"");',
  'const box=$("failures");box.textContent="";',
  'for(const f of (d.report.failures||[])){const p=document.createElement("div");',
  'p.className="bad";',
  'p.textContent=(f.namespace||"")+" "+(f.slug||f.title||"")+" — "+(f.message||f.status||"");',
  'box.append(p);}}}catch(e){}}',
  'function schedule(){clearInterval(timer);timer=setInterval(poll,1500);}',
  '$("search").oninput=e=>{query=e.target.value.trim();renderList();};',
  '$("selectAll").onchange=e=>{const vis=visibleRepos();',
  'if(e.target.checked)vis.forEach(r=>selected.add(r.namespace));',
  'else vis.forEach(r=>selected.delete(r.namespace));renderList();};',
  '$("start").onclick=async()=>{if(!selected.size)return;',
  '$("start").disabled=true;setHint("正在启动…");',
  'try{await api("/api/export",{method:"POST",',
  'headers:{"content-type":"application/json"},',
  'body:JSON.stringify({session:SESSION,repos:[...selected],clean:$("clean").checked})});',
  '$("progressPanel").hidden=false;$("barFill").style.width="8%";}',
  'catch(e){setHint(e.message);$("start").disabled=false;}};',
  '$("reload").onclick=loadRepos;',
  'loadRepos();poll();schedule();',
].join('\n');

export function renderPage({ session }: PageOptions): string {
  return [
    '<!doctype html><html lang="zh-CN"><head><meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    '<title>语雀导出</title><style>', THEME, '</style></head>',
    '<body><main>',
    '<header><h1>语雀导出</h1>',
    '<p class="sub" id="who">正在读取账号…</p></header>',
    // First run: the app has no token yet. Ask for one instead of showing an
    // English API error, and verify it before treating setup as complete.
    '<section class="panel setup" id="setupPanel" hidden>',
    '<h2>先配置语雀 Token</h2>',
    '<p class="muted setup-hint">导出需要你的语雀访问令牌。获取方式：语雀 → 头像 → 设置 → 开发者 → 新建 Token，勾选「读取」权限即可。</p>',
    '<div class="row"><input id="tokenInput" type="password" placeholder="粘贴 Token" aria-label="语雀 Token" autocomplete="off"></div>',
    '<div class="row actions"><button id="saveToken">保存并继续</button>',
    '<button id="openTokenPage" class="ghost">打开获取页面</button>',
    '<span id="tokenHint" class="muted"></span></div>',
    '</section>',
    '<section class="panel" id="mainPanel">',
    '<div class="row"><button id="reload" class="ghost">刷新知识库</button>',
    '<label class="check"><input type="checkbox" id="clean"> 强制重新抓取全部正文</label></div>',
    '<div class="row search-row"><input id="search" type="search" placeholder="搜索知识库名称或 namespace" aria-label="搜索知识库"></div>',
    '<div class="row selectall-row"><label class="check"><input type="checkbox" id="selectAll"> 全选</label>',
    '<span id="visibleCount" class="muted"></span></div>',
    '<div id="list" class="list"><p class="muted">正在加载知识库…</p></div>',
    '<div class="row actions"><button id="start" disabled>开始导出</button>',
    '<span id="count" class="muted">已选 0 个知识库 · 0 篇</span>',
    '<span id="hint" class="muted"></span></div>',
    '</section>',
    '<section class="panel" id="progressPanel" hidden><h2>进度</h2>',
    '<div class="bar"><div class="bar-fill" id="barFill"></div></div>',
    '<p class="muted" id="progressText"></p><pre id="log" class="log"></pre></section>',
    '<section class="panel" id="resultPanel" hidden><h2>上次结果</h2>',
    '<div class="stats" id="stats"></div><div id="failures"></div>',
    '<p class="muted" id="outDir"></p></section>',
    '</main><script>', injectSession(SCRIPT, session), '</script></body></html>',
  ].join('');
}
